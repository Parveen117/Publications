def classify(rho):
    """exact / closed_not_exact / open, decided by exact rank."""
    if d1(rho) != [Fr(0)] * len(FACES):
        return "open"
    # closed: is it a coboundary? solve d0 f = rho by rank comparison
    cols = []
    for v in VERTS:
        f = {u: (Fr(1) if u == v else Fr(0)) for u in VERTS}
        cols.append(d0(f))
    A = [[cols[v][e] for v in range(len(VERTS))]
         for e in range(len(EDGES))]
    Aug = [row[:] + [rho[e]] for e, row in enumerate(A)]
    return "exact" if rank(A) == rank(Aug) else "closed_not_exact"


