KMOD = 6                                    # phase exponents in Z/K


def sheet_act(state, alpha, n):
    """S_(alpha,n): (theta, s, w) -> (theta + alpha, s + n,
    w + omega(alpha, n)) with the cocycle omega(alpha, n) = alpha * n.

    theta is an EXPONENT in Z/KMOD and is never evaluated as a root of
    unity (UGD-1 discipline)."""
    theta, s, w = state
    return ((theta + alpha) % KMOD, s + n, w + alpha * n)


def certify_T5():
    base = (0, 0, 0)
    # group action: composition adds parameters up to the cocycle
    for a1, n1 in ((1, 2), (4, -1), (3, 0)):
        for a2, n2 in ((2, 1), (5, 3), (0, -2)):
            lhs = sheet_act(sheet_act(base, a1, n1), a2, n2)
            direct = sheet_act(base, (a1 + a2) % KMOD, n1 + n2)
            # the winding terms differ by an exact cocycle correction
            assert lhs[0] == direct[0] and lhs[1] == direct[1]
            corr = lhs[2] - direct[2]
            assert corr == a1 * n1 + a2 * n2 - ((a1 + a2) % KMOD) * (
                n1 + n2)

    # a loop with VISIBLE PHASE RETURN but nonzero sheet class
    st = base
    for (a, n) in ((3, 1), (3, 1)):          # total turn 6 = 0 mod K
        st = sheet_act(st, a, n)
    assert st[0] == 0                        # visible phase returns
    assert (st[1], st[2]) != (0, 0)          # sheet index / winding do not
    assert st[1] == 2 and st[2] == 6

    # full closure control: everything returns
    st2 = base
    for (a, n) in ((3, 1), (3, -1)):
        st2 = sheet_act(st2, a, n)
    assert st2[0] == 0 and st2[1] == 0
    st3 = sheet_act(sheet_act(base, 2, 0), 4, 0)
    assert st3 == (0, 0, 0)                  # class vanishes entirely

    # no root of unity is ever formed: phases stay integer exponents
    assert all(isinstance(x, int) for x in (st[0], st[1], st[2]))

    return {
        "statement": (
            "The sheet rotation S_(alpha,n) acts with an exact "
            "cocycle: phase and sheet index add, and the winding terms "
            "differ from the naive sum by an exactly computed cocycle "
            "correction. Phase is carried as an EXPONENT in Z/K and "
            "never evaluated as a root of unity. Certified witness: a "
            "loop with total turn exactly 0 mod K — visible phase "
            "return on the circle — whose sheet index is 2 and winding "
            "6, i.e. a nonzero sheet-rotation class; and controls "
            "where the class vanishes entirely. The visible phase "
            "circle forgets sheet index and winding; the recognition "
            "topology retains them"),
        "K": KMOD,
        "witness_class": [0, 2, 6],
        "verdict": "PASS",
    }


