# Cell complex: vertices 0,1,2,3; edges of the square plus the diagonal
# 0-2; ONE face filled (the triangle 0,1,2). The unfilled triangle
# leaves H^1 of rank exactly 1.

VERTS = (0, 1, 2, 3)
EDGES = ((0, 1), (1, 2), (2, 3), (3, 0), (0, 2))
FACES = (((0, 1), 1), ((1, 2), 1), ((0, 2), -1)),      # one filled face


def rank(M):
    if not M or not M[0]:
        return 0
    A = [row[:] for row in M]
    rows, cols = len(A), len(A[0])
    r = 0
    for c in range(cols):
        piv = next((i for i in range(r, rows) if A[i][c] != 0), None)
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        A[r] = [x / A[r][c] for x in A[r]]
        for i in range(rows):
            if i != r and A[i][c] != 0:
                A[i] = [x - A[i][c] * y for x, y in zip(A[i], A[r])]
        r += 1
    return r


def d0(f):
    """Coboundary of a 0-cochain: alpha(e) = f(head) - f(tail)."""
    return [f[b] - f[a] for (a, b) in EDGES]


def d1(alpha):
    """Coboundary of a 1-cochain: sum of signed edge values per face."""
    out = []
    for face in FACES:
        out.append(sum(s * alpha[EDGES.index(e)] for (e, s) in face))
    return out


def pair(alpha, cycle):
    return sum(a * z for a, z in zip(alpha, cycle))


def boundary(cycle):
    """Vertex boundary of a 1-chain."""
    out = {v: Fr(0) for v in VERTS}
    for (a, b), z in zip(EDGES, cycle):
        out[b] += z
        out[a] -= z
    return out


def certify_T2():
    # d1 d0 = 0 exactly, on a spanning set
    for v in VERTS:
        f = {u: (Fr(1) if u == v else Fr(0)) for u in VERTS}
        assert d1(d0(f)) == [Fr(0)] * len(FACES)

    D0 = [[d0({u: (Fr(1) if u == v else Fr(0)) for u in VERTS})[e]
           for v in VERTS] for e in range(len(EDGES))]
    D1 = [[d1([Fr(1) if i == e else Fr(0)
               for i in range(len(EDGES))])[f]
           for e in range(len(EDGES))] for f in range(len(FACES))]
    r0, r1 = rank(D0), rank(D1)
    assert r0 == 3 and r1 == 1
    h1 = len(EDGES) - r1 - r0                  # 5 - 1 - 3 = 1
    assert h1 == 1

    # two cycles differing by the boundary of the FILLED face
    z_square = [Fr(1), Fr(1), Fr(1), Fr(1), Fr(0)]      # 0-1-2-3-0
    z_big = [Fr(0), Fr(0), Fr(1), Fr(1), Fr(1)]         # 0-2-3-0
    face_bd = [Fr(1), Fr(1), Fr(0), Fr(0), Fr(-1)]      # the filled face
    assert all(x == y for x, y in zip(
        z_square, [a + b for a, b in zip(z_big, face_bd)]))
    for z in (z_square, z_big, face_bd):
        assert all(v == 0 for v in boundary(z).values())

    # a CLOSED cochain: charge equal on homologous cycles
    alpha = [Fr(2), Fr(-1), Fr(3), Fr(1, 2), Fr(1)]
    assert d1(alpha) == [Fr(0)]                       # closed
    assert pair(alpha, z_square) == pair(alpha, z_big)
    assert pair(alpha, face_bd) == 0                  # boundary pairs 0
    assert pair(alpha, z_square) != 0                 # nonzero class

    # a COBOUNDARY has zero charge on every cycle
    beta = d0({0: Fr(0), 1: Fr(5), 2: Fr(-2), 3: Fr(7, 3)})
    assert d1(beta) == [Fr(0)]
    for z in (z_square, z_big, face_bd):
        assert pair(beta, z) == 0

    # a NON-closed cochain is not a class function
    gamma = [Fr(1), Fr(0), Fr(0), Fr(0), Fr(0)]
    assert d1(gamma) != [Fr(0)]
    assert pair(gamma, z_square) != pair(gamma, z_big)

    return {
        "statement": (
            "On an explicit finite complex (square with diagonal, one "
            "face filled) d1 d0 = 0 exactly and H^1 has rank EXACTLY "
            "1. For a CLOSED cochain the seam charge is EQUAL on "
            "homologous cycles — certified with two cycles differing "
            "by the boundary of the filled face — and zero on "
            "boundaries; a coboundary has charge zero on every cycle; "
            "and a non-closed cochain is provably not a class "
            "function. Seam charge is conserved on recognition "
            "homology classes, and a nonzero class is closed but not "
            "locally removable"),
        "H1_rank": h1,
        "verdict": "PASS",
    }


