def gadd(a, b):
    return (a[0] + b[0], a[1] + b[1])


def gmul(a, b):
    return (a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0])


GZ, GO = (Fr(0), Fr(0)), (Fr(1), Fr(0))
GNEG = (Fr(-1), Fr(0))
GI = (Fr(0), Fr(1))


def cm(a, b, c, d):
    return [[a, b], [c, d]]


def cmmul(A, B):
    return [[gadd(gmul(A[i][0], B[0][j]), gmul(A[i][1], B[1][j]))
             for j in range(2)] for i in range(2)]


def cmscale(s, A):
    return [[gmul(s, A[i][j]) for j in range(2)] for i in range(2)]


I2 = cm(GO, GZ, GZ, GO)
R = cm(GZ, GNEG, GO, GZ)          # R^2 = -I
K = cm(GO, GZ, GZ, GNEG)          # K^2 = I
RK = cmmul(R, K)


def word(letters):
    """A KIR transport word, evaluated exactly."""
    W = I2
    for ch in letters:
        W = cmmul(W, {"I": I2, "R": R, "K": K}[ch])
    return W


def shadow(W):
    """Declared shadow projection: forgets an overall scalar factor.

    Two transports have the same visible effect when they differ by a
    scalar multiple; the projection returns a canonical representative.
    """
    for i in range(2):
        for j in range(2):
            z = W[i][j]
            if z != GZ:
                # divide the whole matrix by this entry (exact in Q(i))
                den = z[0] * z[0] + z[1] * z[1]
                inv = (z[0] / den, -z[1] / den)
                return tuple(tuple(gmul(inv, W[r][c]) for c in range(2))
                             for r in range(2))
    return None


