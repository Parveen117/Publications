    # carries the ratio Det(M1)/Det(T_L M0) — no logarithm anywhere
    charges = (Fr(2), Fr(3), Fr(1, 2), Fr(1, 3))
    total = Fr(1)
    for c in charges:
        total *= c
    assert total == 1                          # global determinant RETURNS

    # ... yet subcycle charges are nonzero: the appendix's corollary
    sub1 = charges[0] * charges[1]             # 6
    sub2 = charges[2] * charges[3]             # 1/6
    assert sub1 != 1 and sub2 != 1
    assert sub1 * sub2 == 1

    # composition and refinement: splitting an edge preserves the charge
    split = (Fr(4), Fr(1, 2))                  # 4 * 1/2 = 2 = charges[0]
    assert split[0] * split[1] == charges[0]
    refined = (split[0], split[1]) + charges[1:]
