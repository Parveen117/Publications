def fabric_partition(rails_u, k, m, t, ins, jmax=F(1)):
    """t-row fabric. rails_u[s] = face coefficient dict for rail s (0..t-1);
    k = rung coefficient dict (same for all t-1 rungs per column);
    ins = {(s, column): spin} character insertions. Returns exact rational."""
    labels = [F(x, 2) for x in range(int(2 * jmax) + 1)]
    zero = F(0)
    # cut state: tuple over rails of (a, q, x)
    state = {tuple((zero, zero, zero) for _ in range(t)): Surd.rat(1)}
    for i in range(m):
        last = (i == m - 1)
        new = {}
        for key, amp in state.items():
            # choose next labels per rail
            next_choices = [[(zero,)] if last else [(a,) for a in labels] for _ in range(t)]
            # recursive column contraction over rails with rung indices chained

            def rec(s, prev_rung, coef, idx_acc):
                """s = rail index; prev_rung = (c, y, z) shared with rail s-1 or None."""
                if s == t:
                    nk = tuple(idx_acc)
                    new[nk] = new.get(nk, Surd()) + amp * coef
                    return
                a, q, x = key[s]
                j_ins = ins.get((s, i + 1), F(0))
                for (an,) in next_choices[s]:
                    cf = coef if last else coef * rails_u[s][an] * (2 * an + 1)
                    if cf.is_zero() if isinstance(cf, Surd) else cf == 0:
                        continue
                    # rung below this rail (to rail s+1) if s < t-1
                    if s < t - 1:
                        rung_choices = [(c,) for c in labels]
                    else:
                        rung_choices = [(zero,)]
                    for (c,) in rung_choices:
                        kc = F(1) if s == t - 1 else k[c] * (2 * c + 1)
                        if kc == 0:
                            continue
                        # vertex tensor: incoming rung from above (prev_rung) and
                        # outgoing rung below. The YM-30 tensor has ONE rung per
                        # vertex; interior rails have two. We realise two rungs by
                        # fusing the rung-above index pair into the insertion slot:
                        # handled by splitting: rail 0 (top) has only the rung below
                        # (plain); rail t-1 (bottom) only the rung above (conj);
                        # interior rails: rung above conj, rung below plain -> use
                        # the 5-leg tensor below.
                        tens = vertex_tensor(a, an, j_ins,
                                             above=None if s == 0 else prev_rung[0],
                                             below=None if s == t - 1 else c)
                        for ikey, val in tens.items():
                            (q1, x1, qp, xp, ya, za, yb, zb) = ikey
                            if (q1, x1) != (q, x):
                                continue
                            if prev_rung is not None and (ya, za) != (prev_rung[1], prev_rung[2]):
                                continue
                            rec(s + 1, (c, yb, zb) if s < t - 1 else None,
                                cf * kc * val, idx_acc + [(an, qp, xp)])
            rec(0, None, Surd.rat(1), [])
        state = new
    total = state.get(tuple((zero, zero, zero) for _ in range(t)), Surd())
    assert total.is_rational(), ("surd did not cancel", total.t)
    return total.rational()


_VT = {}


def vertex_tensor(a_prev, a_next, j_ins, above, below):
    """Rail vertex with incoming edge a_prev (q,x), outgoing a_next (qp,xp),
    optional rung above (label `above`, indices (ya,za), conjugate factor),
    optional rung below (label `below`, indices (yb,zb), plain factor),
    and a traced insertion chi_{j_ins}. Built from the YM-32 4-valent
    tensor by fusing the rung-above factor into the insertion slot via
    a second CG reduction. Keys: (q,x,qp,xp,ya,za,yb,zb); absent rungs
    carry (0,0)."""
    key = (a_prev, a_next, j_ins, above, below)
    if key in _VT:
        return _VT[key]
    from ym30_recoupling_engine import cg, eps, ms, vertex
    zero = F(0)
    out = {}
    A = above if above is not None else zero
    B = below if below is not None else zero
    # enumerate all index choices
    for q in ms(a_prev):
        for x in ms(a_prev):
            for qp in ms(a_next):
                for xp in ms(a_next):
                    for ya in ms(A):
                        for za in ms(A):
                            for yb in ms(B):
                                for zb in ms(B):
                                    tot = Surd()
                                    # factors at the vertex (all as plain D after eps):
                                    # D^{a_prev}_{q x}, conj D^{a_next}_{qp xp},
                                    # conj D^{A}_{ya za} (rung above), D^{B}_{yb zb} (rung below),
                                    # chi_{j}: sum_s D^{j}_{s s}.
                                    # Fuse: first D^{a_prev} x D^{j} -> D^{e1}; then D^{e1} x D^{B} -> D^{e2};
                                    # then three-D integral with conj D^{a_next} and conj D^{A} fused:
                                    # conj(D^{a_next}) conj(D^{A}) = conj(D^{a_next} D^{A}) -> conj D^{e3}.
                                    for s in ms(j_ins):
                                        for e1 in _fuse(a_prev, j_ins):
                                            for M1 in ms(e1):
                                                c1 = cg(a_prev, q, j_ins, s, e1, M1)
                                                if c1.is_zero():
                                                    continue
                                                for N1 in ms(e1):
                                                    c2 = cg(a_prev, x, j_ins, s, e1, N1)
                                                    if c2.is_zero():
                                                        continue
                                                    for e2 in _fuse(e1, B):
                                                        for M2 in ms(e2):
                                                            c3 = cg(e1, M1, B, yb, e2, M2)
                                                            if c3.is_zero():
                                                                continue
                                                            for N2 in ms(e2):
                                                                c4 = cg(e1, N1, B, zb, e2, N2)
                                                                if c4.is_zero():
                                                                    continue
                                                                for e3 in _fuse(a_next, A):
                                                                    for M3 in ms(e3):
                                                                        c5 = cg(a_next, qp, A, ya, e3, M3)
                                                                        if c5.is_zero():
                                                                            continue
                                                                        for N3 in ms(e3):
                                                                            c6 = cg(a_next, xp, A, za, e3, N3)
                                                                            if c6.is_zero():
                                                                                continue
                                                                            # conj D^{e3}_{M3 N3} -> eps
                                                                            for Ma in ms(e3):
                                                                                e_1 = eps(e3, M3, Ma)
                                                                                if e_1 == 0:
                                                                                    continue
                                                                                for Na in ms(e3):
                                                                                    e_2 = eps(e3, N3, Na)
                                                                                    if e_2 == 0:
                                                                                        continue
                                                                                    # Int D^{e2}_{M2 N2} D^{e3}_{Ma Na} dg = delta/d
                                                                                    if e2 != e3:
                                                                                        continue
                                                                                    v = vertex(e2, M2, N2, e3, Ma, Na, zero, zero, zero)
                                                                                    tot = tot + c1 * c2 * c3 * c4 * c5 * c6 * v * (e_1 * e_2)
                                    if not tot.is_zero():
                                        out[(q, x, qp, xp, ya, za, yb, zb)] = tot
    _VT[key] = out
    return out


def _fuse(j1, j2):
    lo = abs(j1 - j2)
    return [lo + F(n) for n in range(int(2 * min(j1, j2)) + 1)]


