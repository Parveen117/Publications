import os, sys, json
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "certificates"))
import ym40_hk_ladder as ym40  # noqa: E402


def test_outward_rounding_certified():
    x = F(1, 3)
    assert ym40.rdn(x) <= x <= ym40.rup(x)
    assert ym40.rup(x) - ym40.rdn(x) <= F(2, 10 ** 30)


def test_gamma_bracket_encloses_simple_case():
    # rho = 1/2, a = 1: gamma = log 2 in [0.693147180, 0.693147181]
    lo, hi = ym40.gamma_bracket(F(1, 2), F(0), F(1))
    assert lo <= F(693147181, 10 ** 9) and hi >= F(693147180, 10 ** 9)
    assert hi - lo < F(1, 10 ** 8)


def test_verdict_and_pin():
    # full run regenerated by its own CI step (~4 min); here check the committed
    # result against the pin and re-verify the T3/T5 inequalities from the stored numbers
    cdir = os.path.join(HERE, "..", "certificates")
    cert = json.load(open(os.path.join(cdir, "YM40_RESULT.json")))
    assert cert["verdict"] == "PASS"
    pin = open(os.path.join(cdir, "EXPECTED_YM40.sha256")).read().strip()
    assert ym40.canonical_sha(cert) == pin
    prev = None
    for a in ("1", "1/4", "1/16", "1/64"):
        g = cert["grid"][a]
        d_lo, d_hi = F(g["Delta_gamma"][0]), F(g["Delta_gamma"][1])
        assert d_lo >= 1
        eps = max(abs(d_lo - F(5, 4)), abs(d_hi - F(5, 4)))
        if prev is not None:
            assert eps < prev
        prev = eps
