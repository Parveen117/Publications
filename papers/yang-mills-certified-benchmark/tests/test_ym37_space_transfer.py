import os, sys
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "certificates"))
import ym37_space_transfer as ym37  # noqa: E402

Z, H, O = F(0), F(1, 2), F(1)
U0 = {Z: F(1), H: F(1, 3), O: F(1, 10)}
K0 = {Z: F(1), H: F(2, 5), O: F(1, 10)}


def test_s3_moments_exact():
    assert ym37.moment4((2, 0, 0, 0)) == F(1, 4)
    assert ym37.moment4((4, 0, 0, 0)) == F(1, 8)
    assert ym37.moment4((2, 2, 0, 0)) == F(1, 24)
    assert ym37.moment4((1, 0, 0, 0)) == 0


def test_even_invariant_sector_matches_ym33_engine():
    from ym33_t_row_engine import fabric_partition
    b, M, N, B, e0 = ym37.build_pencil(2, U0, K0)
    assert len(b) == 8
    assert ym37.z_seq(M, B, e0, 3) == fabric_partition([U0, U0], K0, 3, 2, {})
    assert ym37.a_seq(M, N, B, e0, 3, 2) == fabric_partition([U0, U0], K0, 3, 2, {(0, 2): H, (1, 2): H})


def test_t53_weight_refusal_witness():
    W = [[F(1, 2), F(1, 2)], [F(1, 2), F(1, 2)]]
    I = [[F(1), F(0)], [F(0), F(1)]]
    assert ym37.count_above(W, I, F(1, 2)) == 1   # lambda_max = 1 > every diagonal = 1/2


def test_verdict_and_pin():
    # the full run (t = 3 sector, dim 52) takes ~16 min and is regenerated by its own CI
    # step; here the committed result is checked against the pin, and the t = 2 half is
    # regenerated and compared entry by entry.
    import json
    cdir = os.path.join(HERE, "..", "certificates")
    cert = json.load(open(os.path.join(cdir, "YM37_RESULT.json")))
    assert cert["verdict"] == "PASS"
    pin = open(os.path.join(cdir, "EXPECTED_YM37.sha256")).read().strip()
    assert ym37.canonical_sha(cert) == pin
    fresh = ym37.run(do_t3=False)
    assert fresh["verdict"] == "PASS"
    for kap, v in fresh["grid"].items():
        assert v["t2"] == cert["grid"][kap]["t2"]
